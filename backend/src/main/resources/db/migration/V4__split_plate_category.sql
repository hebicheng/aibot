-- 板材分类拆分：涂镀/中厚板/花纹板/冷轧卷 从「建材」移入「板材」
-- 背景：上游数据源（创大钢铁 jiage.cdgtw.net）中「板材」为独立分类，
--       其子项为 涂镀(180)/中厚板(203)/花纹板(160)/冷轧卷(150)。
--       V3 建数据时被合并进「建材」，此处拆出。
-- 说明：分类顺序由 sort_order 决定，拆分后板材(50-80) 自然位于 建材(10-40) 之后、
--       不锈钢(110+) 之前，无需调整 sort_order；前后端均为动态读取 category，零代码改动。
UPDATE market_products
SET category = '板材'
WHERE code IN ('180', '203', '160', '150');
